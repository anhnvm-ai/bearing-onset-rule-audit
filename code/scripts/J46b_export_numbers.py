"""J46b -- write the indicator-robustness macros (J46) into paper/ieee/revision_numbers.tex.

Idempotent between its markers, as J39b, J41b and J43b are.

  j46_indicator_r2.csv   one row per dataset x indicator: which way it moves, how many designs could be
                         fitted, and the R^2 of the size term against that of the family label

Run after J46:  python scripts/J46b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E3 BEGIN (generated by scripts/J46b_export_numbers.py; do not edit by hand)"
END = "% ---- E3 END"
DS = {"xjtu": "Xjtu", "femto": "Femto"}
# how the text names an indicator when it has to name one; the keys are the columns J45 writes
NAMES = {"rms": "RMS", "std": "the standard deviation", "p2p": "the peak-to-peak amplitude",
         "absmax": "the maximum absolute amplitude", "crest": "the crest factor", "kurtosis": "the kurtosis",
         "skew": "the skewness", "v_rms": "RMS", "v_p2p": "the peak-to-peak amplitude",
         "v_absmax": "the maximum absolute amplitude", "v_crest": "the crest factor",
         "v_kurtosis": "the kurtosis", "spec_centroid": "the spectral centroid",
         "band_power_fixed": "the power in the fixed band", "band_power_auto": "the power in the fitted band",
         "env_rms": "the envelope RMS", "env_kurtosis": "the envelope kurtosis"}


def three(x: float) -> str:
    return f"{x:.3f}"


def main() -> int:
    s = pd.read_csv(TABLES / "j46_indicator_r2.csv")
    fitted = s[s.r2_size.notna()]

    lines = [BEGIN,
             "% E3: the sweep repeated on every indicator, including the spectral and envelope ones (J45, J46)"]
    lines += [
        f"\\newcommand{{\\IndPairs}}{{{len(fitted)}}}"
        f"   % dataset-indicator pairs on which the 67-design sweep could be fitted",
        f"\\newcommand{{\\IndSizeWins}}{{{int((fitted.r2_size > fitted.r2_family).sum())}}}"
        f"   % of those, the number on which the size term explains more than the family label",
        f"\\newcommand{{\\IndKinds}}{{{fitted.kind.nunique()}}}"
        f"   % kinds of indicator: {', '.join(sorted(fitted.kind.unique()))}",
    ]
    for ds, tag in DS.items():
        d = fitted[fitted.dataset == ds]
        all_ds = s[s.dataset == ds]
        lines += [
            f"\\newcommand{{\\IndN{tag}}}{{{len(d)}}}"
            f"   % indicators fitted on this dataset, of {len(all_ds)} extracted",
            f"\\newcommand{{\\IndRise{tag}}}{{{int((all_ds.direction_sd > 0).sum())}}}"
            f"   % of those, the number that RISE as the bearing degrades; the ten rules fire on no other",
        ]
        for kind, tagk in (("envelope", "Env"), ("spectrum", "Spec")):
            g = d[d.kind == kind]
            if not len(g):
                continue
            lines.append(f"\\newcommand{{\\Ind{tagk}Size{tag}}}{{{three(g.r2_size.median())}}}"
                         f"\\newcommand{{\\Ind{tagk}Family{tag}}}{{{three(g.r2_family.median())}}}"
                         f"   % median over the {len(g)} {kind} indicators")
    # the indicator that falls hardest, named in the text as the reason a rule cannot fire on it
    worst = s.loc[s.direction_sd.idxmin()]
    lines.append(f"\\newcommand{{\\IndFallsMost}}{{{worst.direction_sd:.1f}}}"
                 f"   % {worst.indicator} on {worst.dataset}: how far it moves by the end of life, in baseline sd")
    # and its name, so that the sentence naming it cannot drift from the row it is taken from
    lines.append(f"\\newcommand{{\\IndFallsMostName}}{{{NAMES[worst.indicator]}}}"
                 f"   % how the text says {worst.indicator}")
    # how many designs the FEMTO spectral fits rest on: they fire on two or three bearings of 13
    _sf = fitted[(fitted.dataset == "femto") & (fitted.kind == "spectrum")].n_designs_fitted
    lines.append(f"\\newcommand{{\\IndSpecDesignsFemto}}{{{_sf.min()} to {_sf.max()}}}"
                 f"   % of {int(s.n_designs_fitted.max())}, over the {len(_sf)} spectral indicators")
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macro lines into {TARGET.name}")
    for l in lines[2:-1]:
        print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
