"""J39b -- write the B1/B2 macros (J38, J39) into paper/ieee/revision_numbers.tex, between fixed markers.

Idempotent: the block between the markers is replaced on every run, nothing else in the file is touched.
Every value is read from the CSVs; nothing is typed by hand.

  B1  j38_ratio_bootstrap.csv  the bearing-bootstrap interval of the pooled labeller/model factor (7.6, 5.1)
  B2  j39_two_stage.csv        the two-stage exponential fit of the form of [2], [9]: RMSE and skill per cell
      j39_two_stage_compare.csv  its labeller spread against the spread over the seven models

Run after J38 and J39:  python scripts/J39b_export_numbers.py
"""
import math
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- B1/B2 BEGIN (generated by scripts/J39b_export_numbers.py; do not edit by hand)"
END = "% ---- B1/B2 END"
VARIANT = "exp"          # the exponential form of [2], [9]; J39 found it stable (no jump > 0.5 on short bearings)
LAB_TAG = {"3sig_rms": "Rms", "ma5sig": "MaFive", "ewma": "Ewma", "pct05": "Pct"}
DS_TAG = {"xjtu": "Xjtu", "femto": "Femto"}


def one(x):
    return f"{x:.1f}"


def three(x):
    return f"{x:.3f}"


def signed2(x):
    return f"{x:+.2f}"


def thin(n):
    """IEEE Editorial Style Manual: 62 000 and 100 000 with thin spaces, but 4000."""
    return f"{n:,}".replace(",", "\\,") if n >= 10000 else str(n)


def main():
    b1 = pd.read_csv(TABLES / "j38_ratio_bootstrap.csv")
    ts = pd.read_csv(TABLES / "j39_two_stage.csv")
    cmp_ = pd.read_csv(TABLES / "j39_two_stage_compare.csv")
    lines = [BEGIN,
             "% B1: j38_ratio_bootstrap.csv -- 20,000 resamples of whole bearings, seed 0, held-out predictions fixed"]
    for ds, tag in DS_TAG.items():
        r = b1[(b1.dataset == ds) & (b1.scale == "rmse")].iloc[0]
        n_dir = int(round(r.share_label_gt_model * r.n_boot))
        lines += [
            f"\\newcommand{{\\DownRatioCi{tag}}}{{[{one(r.factor_lo)}, {one(r.factor_hi)}]}}"
            f"   % 95% interval of the pooled factor {r.factor:.3f}",
            f"\\newcommand{{\\DownRatioBootMed{tag}}}{{{one(r.factor_boot_median)}}}"
            f"   % bootstrap median, below the point value: the point estimate is optimistic",
            # IEEE: a thin space, not a comma, in numbers of five or more digits (20 000; but 4000)
            f"\\newcommand{{\\DownRatioDir{tag}}}{{{thin(n_dir)}}}"
            f"   % resamples of {int(r.n_boot):,} in which the labeller spread is the larger",
        ]
    lines.append("% B2: j39_two_stage.csv / j39_two_stage_compare.csv, variant '" + VARIANT + "' (exponential)")
    for ds, tag in DS_TAG.items():
        d = ts[(ts.dataset == ds) & (ts.variant == VARIANT)].set_index("labeller")
        for lab, lt in LAB_TAG.items():
            lines.append(f"\\newcommand{{\\TwoStRmse{tag}{lt}}}{{{three(d.loc[lab, 'rmse'])}}}"
                         f"\\newcommand{{\\TwoStSkill{tag}{lt}}}{{{signed2(d.loc[lab, 'skill'])}}}")
        c = cmp_[(cmp_.dataset == ds) & (cmp_.variant == VARIANT)].iloc[0]
        lines += [
            f"\\newcommand{{\\TwoStLabelSpread{tag}}}{{{three(c.two_stage_label_spread)}}}"
            f"   % max - min over the 4 labellers of the two-stage RMSE",
            f"\\newcommand{{\\TwoStModelGap{tag}}}{{{three(c.seven_model_spread_max)}}}"
            f"   % largest spread over the 7 models (6 regressors + two-stage) with the labeller fixed",
            f"\\newcommand{{\\TwoStDirPct{tag}}}{{{100 * c.share_ls2_gt_max_ms7:.1f}}}"
            f"   % % of resamples in which the first exceeds the second",
        ]
        e = d.loc["ewma"]
        lines.append(f"\\newcommand{{\\TwoStEwmaOverPct{tag}}}{{{100 * e.post_onset_share_over_0p25:.0f}}}"
                     f"   % % of post-onset records predicted more than 0.25 too long under ewma"
                     f" (mean signed error {e.post_onset_mean_signed_error:+.3f})")
    # one number for both datasets in note b, rounded DOWN so that "at least" stays true
    lo = min(cmp_[cmp_.variant == VARIANT].share_ls2_gt_max_ms7) * 100
    lines.append(f"\\newcommand{{\\TwoStDirPctMin}}{{{math.floor(lo * 10) / 10:.1f}}}"
                 f"   % the smaller of the two shares above ({lo:.2f}), rounded down")
    lines.append(END)
    block = "\n".join(lines)

    text = TARGET.read_text(encoding="utf-8")
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pat.search(text):
        text = pat.sub(lambda m: block, text)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(block)


if __name__ == "__main__":
    main()
