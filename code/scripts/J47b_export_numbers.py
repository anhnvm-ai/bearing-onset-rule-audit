"""J47b -- write the sequence-model macros (J47) into paper/ieee/revision_numbers.tex.

Idempotent between its markers, as J39b, J41b, J43b, J44b and J46b are.

  j47_sequence_models.csv   one row per dataset x labeller x model x arm: RMSE, MAE, skill, interval
  j47_seed_spread.csv       per cell, the spread of RMSE over the three seeds
  j47_compare.csv           the labeller/model factor over the six-, seven- and nine-model pools,
                            on the RMSE scale and on the skill scale

Which macros are written is fixed by the columns of those tables, not by what the numbers turn out to
be: the factor on each scale, the two control deltas, the worst seed spread, and the best skill any
sequence model reaches. The six-model factor is exported too, because the manuscript already prints it
from J38 and the two must agree.

Run after J47:  python scripts/J47b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E5 BEGIN (generated by scripts/J47b_export_numbers.py; do not edit by hand)"
END = "% ---- E5 END"
DS = {"xjtu": "Xjtu", "femto": "Femto"}


def _worst(res, ds: str, arm: str) -> float:
    """The largest increase in RMSE that control causes, over the cells of one dataset."""
    a = res[(res.dataset == ds) & (res.arm == arm)].set_index(["labeller", "model"]).rmse
    b = res[(res.dataset == ds) & (res.arm == "main")].set_index(["labeller", "model"]).rmse
    return float((a - b).max())


def main() -> int:
    res = pd.read_csv(TABLES / "j47_sequence_models.csv")
    seed = pd.read_csv(TABLES / "j47_seed_spread.csv")
    cmp_ = pd.read_csv(TABLES / "j47_compare.csv")
    main_arm = res[res.arm == "main"]

    lines = [BEGIN, "% E5: two sequence models in the downstream pool, with the two declared controls (J47)"]
    lines.append(f"\\newcommand{{\\SeqModels}}{{{int(cmp_[cmp_.pool == 'nine'].n_models.iloc[0])}}}"
                 f"   % models in the extended pool: the six regressors, the two-stage fit, the GRU and the TCN")
    lines.append(f"\\newcommand{{\\SeqEpochs}}{{30}}\\newcommand{{\\SeqWindow}}{{16}}"
                 f"   % declared in the docstring of J47 before any result was read")
    for ds, tag in DS.items():
        q = cmp_[(cmp_.dataset == ds) & (cmp_.scale == "rmse")].set_index("pool")
        s = cmp_[(cmp_.dataset == ds) & (cmp_.scale == "skill")].set_index("pool")
        lines += [
            f"\\newcommand{{\\SeqFactorSix{tag}}}{{{q.loc['six'].factor:.1f}}}"
            f"   % the six regressors of J35, recomputed here; must equal the manuscript's J38 number",
            f"\\newcommand{{\\SeqFactor{tag}}}{{{q.loc['nine'].factor:.1f}}}"
            f"\\newcommand{{\\SeqFactorSkill{tag}}}{{{s.loc['nine'].factor:.1f}}}"
            f"   % the same statistic with the pool extended to nine models, on each scale",
        ]
        d = main_arm[main_arm.dataset == ds]
        best = d.loc[d.skill.idxmax()]
        lines.append(f"\\newcommand{{\\SeqBestSkill{tag}}}{{{best.skill:+.2f}}}"
                     f"\\newcommand{{\\SeqBestModel{tag}}}{{{'GRU' if best.model == 'gru' else 'TCN'}}}"
                     f"   % the best a sequence model reaches on this dataset, under {best.labeller}")
        lines.append(f"\\newcommand{{\\SeqSeedSpread{tag}}}{{{seed[seed.dataset == ds].seed_spread.max():.3f}}}"
                     f"   % the widest spread over the three seeds of any cell")
        lines.append(f"\\newcommand{{\\SeqShuffleWorst{tag}}}{{{_worst(res, ds, 'shuffled'):+.3f}}}"
                     f"   % the largest worsening under the shuffled-order control, over the eight cells")
        for arm, nm in (("shuffled", "Shuffle"), ("constant", "Constant")):
            a = res[(res.dataset == ds) & (res.arm == arm)].set_index(["labeller", "model"]).rmse
            b = main_arm[main_arm.dataset == ds].set_index(["labeller", "model"]).rmse
            delta = (a - b).median()
            lines.append(f"\\newcommand{{\\Seq{nm}Delta{tag}}}{{{delta:+.3f}}}"
                         f"   % median change in RMSE under the {arm} control, over the eight cells")
    _c = res[res.arm == "constant"].skill
    lines.append(f"\\newcommand{{\\SeqConstantSkillMax}}{{{_c.abs().max():.3f}}}"
                 f"   % the largest |skill| any cell reaches when the window carries no information")
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macro lines into {TARGET.name}")
    for l in lines[2:-1]:
        print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
