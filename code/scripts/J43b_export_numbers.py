"""J43b -- write the Phase 2 macros (J42 dispersion, J43 held-out bearings) into revision_numbers.tex.

Idempotent between its markers, as J39b and J41b are. Every value comes from the tables.

  j42_dispersion.csv        the labeller-versus-model comparison under statistics that do not grow with
                            the number of levels, with bearing-bootstrap intervals
  j43_heldout_summary.csv   the curve fitted on half the bearings and applied to the design measurements
                            of the other half, with the split-half reliability that bounds it

Run after J42 and J43:  python scripts/J43b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E2 BEGIN (generated by scripts/J43b_export_numbers.py; do not edit by hand)"
END = "% ---- E2 END"
DS = {"xjtu": "Xjtu", "femto": "Femto"}


def one(x: float) -> str:
    return f"{x:.1f}"


def three(x: float) -> str:
    return f"{x:.3f}"


def signed3(x: float) -> str:
    return f"{x:+.3f}"


def main() -> int:
    disp = pd.read_csv(TABLES / "j42_dispersion.csv").set_index(["dataset", "statistic"])
    held = pd.read_csv(TABLES / "j43_heldout_summary.csv").set_index(["dataset", "model"])

    lines = [BEGIN, "% E2a: pool-size-invariant dispersion (scripts/J42_dispersion_statistics.py)"]
    for ds, tag in DS.items():
        d = disp.loc[ds]
        inv = d.drop(index="range")                      # every statistic that does not grow with the pool
        lines += [
            f"\\newcommand{{\\DispRangeD{tag}}}{{{one(d.loc['range_over_d2'].ratio)}}}"
            f"   % the same ratio with each range divided by the expected range of its pool size",
            f"\\newcommand{{\\DispSd{tag}}}{{{one(d.loc['sd_main_effects'].ratio)}}}"
            f"   % standard deviations of the two sets of main effects",
            f"\\newcommand{{\\DispMin{tag}}}{{{one(inv.ratio.min())}}}"
            f"\\newcommand{{\\DispMax{tag}}}{{{one(inv.ratio.max())}}}"
            f"   % the range of the ratio over the four pool-size-invariant statistics",
            f"\\newcommand{{\\DispDirPct{tag}}}{{{100 * inv.share_ratio_gt_1.min():.1f}}}"
            f"   % the smallest share of resamples, over those statistics, in which the labeller spread is the larger",
        ]
    lines.append("% E2b: held-out bearings (scripts/J43_heldout_bearings.py)")
    for ds, tag in DS.items():
        s, f = held.loc[(ds, "size")], held.loc[(ds, "family")]
        lines += [
            f"\\newcommand{{\\HeldOutSize{tag}}}{{{signed3(s['median'])}}}"
            f"\\newcommand{{\\HeldOutSizeCi{tag}}}{{[{signed3(s.lo)}, {signed3(s.hi)}]}}"
            f"   % median out-of-sample R^2 of the size term over {int(s.n_splits):,} random halves of the bearings",
            f"\\newcommand{{\\HeldOutFamily{tag}}}{{{signed3(f['median'])}}}"
            f"   % the family label on the same splits",
            f"\\newcommand{{\\HeldOutSizeBetter{tag}}}{{{100 * f.share_size_better:.0f}}}"
            f"   % % of splits in which the size term predicts the held-out half better than the family label",
            f"\\newcommand{{\\HeldOutRel{tag}}}{{{signed3(s.split_half_reliability_median)}}}"
            f"\\newcommand{{\\HeldOutCeiling{tag}}}{{{three(s.ceiling_r2)}}}"
            f"   % how far a design's rho agrees between the two halves, and the ceiling that sets",
        ]
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macro lines into {TARGET.name}")
    for l in lines[2:-1]:
        if l.startswith("\\newcommand"):
            print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
