"""J49b -- write the censoring macros (J49) into paper/ieee/revision_numbers.tex.

Idempotent between its markers, as the other exporters are.

  j49_censoring_abc.csv   one row per dataset x rule: the positive rate under each of the three
                          treatments of a trajectory the rule never fires on

The macros are the ones the supplementary text needs to describe Fig. S5 without typing a number by
hand: the cells in which the three treatments can differ at all, the widest of them, and whether the
Kaplan-Meier estimate is the lower one in every such cell.

Run after J49:  python scripts/J49b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E7 BEGIN (generated by scripts/J49b_export_numbers.py; do not edit by hand)"
END = "% ---- E7 END"


def main() -> int:
    d = pd.read_csv(TABLES / "j49_censoring_abc.csv")
    cens = d[d.n_fired < d.n_traj].copy()
    cens["drop_pooled"] = cens.a_exclude_pooled - cens.b_healthy_pooled
    worst = cens.loc[cens.drop_pooled.idxmax()]
    km_lower = int((cens.c_censored_traj < cens.a_exclude_traj).sum())

    lines = [BEGIN, "% E7: the three treatments of a trajectory a rule never fires on (J49)"]
    lines += [
        f"\\newcommand{{\\CensCells}}{{{len(cens)}}}"
        f"\\newcommand{{\\CensCellsAll}}{{{len(d)}}}"
        f"   % dataset-rule cells in which a rule does not fire on every trajectory, of all cells drawn",
        f"\\newcommand{{\\CensWorstRule}}{{\\texttt{{{worst.rule.replace('_', chr(92) + '_')}}}}}"
        f"\\newcommand{{\\CensWorstFired}}{{{int(worst.n_fired)}}}"
        f"\\newcommand{{\\CensWorstTraj}}{{{int(worst.n_traj)}}}"
        f"   % the cell where excluding and labelling healthy differ most, on {worst.dataset}",
        f"\\newcommand{{\\CensWorstExclude}}{{{worst.a_exclude_pooled:.3f}}}"
        f"\\newcommand{{\\CensWorstHealthy}}{{{worst.b_healthy_pooled:.3f}}}"
        f"   % its record-pooled positive rate under the two treatments",
        f"\\newcommand{{\\CensKmLower}}{{{km_lower}}}"
        f"   % of the {len(cens)} censored cells, the number in which Kaplan-Meier is the lower estimate",
    ]
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macro lines into {TARGET.name}")
    for l in lines[2:-1]:
        print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
