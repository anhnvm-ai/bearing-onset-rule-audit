"""J41b -- write the estimand-separation macros (J41) into paper/ieee/revision_numbers.tex.

Idempotent: the block between the markers is replaced on every run and nothing else in the file is
touched, exactly as J39b does for the B1/B2 numbers. Every value is read from the J41 tables.

  j41_estimand_r2.csv            in-sample R^2 of rho(i, n) under four explanations
  j41_estimand_bootstrap.csv     the same, recomputed inside 20,000 resamples of whole bearings
  j41_nominal_conventions.csv    the a-priori shift under four conventions
  j41_cross_family_nominal.csv   fitted on one family, applied to the other, with the a-priori shift

Run after J41:  python scripts/J41b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E1 BEGIN (generated by scripts/J41b_export_numbers.py; do not edit by hand)"
END = "% ---- E1 END"
DS = {"xjtu": "Xjtu", "femto": "Femto"}


def three(x: float) -> str:
    return f"{x:.3f}"


def signed3(x: float) -> str:
    return f"{x:+.3f}"


def main() -> int:
    r2 = pd.read_csv(TABLES / "j41_estimand_r2.csv").set_index(["dataset", "model"]).r2
    bt = pd.read_csv(TABLES / "j41_estimand_bootstrap.csv")
    cv = pd.read_csv(TABLES / "j41_nominal_conventions.csv")
    cf = pd.read_csv(TABLES / "j41_cross_family_nominal.csv")
    sw = pd.read_csv(TABLES / "j26_design_sweep.csv")

    lines = [BEGIN,
             "% E1: is the response-size relation a finding, or a change of variables? (scripts/J41_estimand_separation.py)"]
    for ds, tag in DS.items():
        b = bt[bt.dataset == ds]
        lines += [
            f"\\newcommand{{\\NomRSq{tag}}}{{{three(r2[(ds, 'nominal_shift')])}}}"
            f"   % R^2 of rho on a shift read off the design's parameters, no bearing seen",
            f"\\newcommand{{\\FracRSq{tag}}}{{{three(r2[(ds, 'onset_fraction')])}}}"
            f"   % R^2 of rho on the median life fraction at which the design fires",
            f"\\newcommand{{\\NomBoot{tag}}}{{{signed3(np.median(b.nominal_shift))}}}"
            f"\\newcommand{{\\NomBootCi{tag}}}{{[{signed3(np.percentile(b.nominal_shift, 2.5))}, "
            f"{signed3(np.percentile(b.nominal_shift, 97.5))}]}}"
            f"   % bearing-resampled median and 95% interval over {len(b):,} usable resamples",
            f"\\newcommand{{\\NomBeatsFamily{tag}}}{{{100 * (b.nominal_shift > b.family).mean():.1f}}}"
            f"   % % of resamples in which the a-priori shift explains more than the family label",
            f"\\newcommand{{\\FracLarger{tag}}}{{{100 * (b.onset_fraction > b.nominal_shift).mean():.1f}}}"
            f"   % % of resamples in which onset fraction explains more than the a-priori shift",
            f"\\newcommand{{\\NomAddsOnFrac{tag}}}{{{signed3(np.median(b.fraction_plus_nominal - b.onset_fraction))}}}"
            f"   % what the a-priori shift adds on top of onset fraction, median over resamples",
        ]
        # how tightly the two readings of the same design property move together, from the sweep itself
        s = sw[(sw.dataset == ds) & sw.median_shift_sd.notna() & sw.median_onset_fraction.notna()]
        rho_mf = float(np.corrcoef(np.log(s.median_shift_sd.to_numpy(float)),
                                   s.median_onset_fraction.to_numpy(float))[0, 1])
        lines.append(f"\\newcommand{{\\MeasFracCorr{tag}}}{{{signed3(rho_mf)}}}"
                     f"   % corr(log measured shift, median onset fraction) over the {len(s)} designs")
        # the split of Section IV-C: the conventional charts, and the class it keeps apart
        d = cf[(cf.dataset == ds) & (cf.direction == "detectors -> conventional charts")].iloc[0]
        nv = cf[(cf.dataset == ds) & (cf.direction == "detectors -> novel charts")].iloc[0]
        lines += [
            f"\\newcommand{{\\NomCross{tag}}}{{{signed3(d.r2_oos)}}}"
            f"   % fitted on the {int(d.n_train)} detectors, applied to the {int(d.n_test)} conventional charts",
            f"\\newcommand{{\\NomCrossNovel{tag}}}{{{signed3(nv.r2_oos)}}}"
            f"   % the same fit on the {int(nv.n_test)} AR-corrected and adaptive designs, which the "
            f"measured-shift curve does not reach",
        ]
        c = cv[cv.dataset == ds].set_index("convention").r2
        keep = [k for k in c.index if not k.startswith("D_")]   # D is the deliberate control, reported apart
        lines += [
            f"\\newcommand{{\\NomConvMin{tag}}}{{{three(c[keep].min())}}}"
            f"\\newcommand{{\\NomConvMax{tag}}}{{{three(c[keep].max())}}}"
            f"   % range over the three defensible conventions; the control that misstates the EWMA limit gives "
            f"{c['D_ewma_L_only']:.3f}",
            f"\\newcommand{{\\NomConvCtrl{tag}}}{{{three(c['D_ewma_L_only'])}}}"
            f"   % dropping the sqrt(lambda/(2-lambda)) factor the EWMA limit has",
        ]
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        # a lambda, so that the backslashes of \newcommand are not read as replacement escapes
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macros into {TARGET.name}")
    for l in lines[2:-1]:
        print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
