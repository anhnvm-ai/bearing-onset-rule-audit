"""J48b -- write the extended-pool dispersion macros (J48) into paper/ieee/revision_numbers.tex.

Idempotent between its markers, as the other exporters are.

  j48_dispersion_extended.csv   dataset x pool x statistic: the two dispersions, their ratio, a 95%
                                bearing-bootstrap interval, and the share of resamples in which the
                                labeller axis is the larger

The macros are the ones a reader needs to check the claim that the ratio of raw ranges is pool-dependent
while the corrected statistics are not: for each dataset, the raw range ratio and the SD-of-main-effects
ratio on the nine-model pool, the interval and share of the one cell that is no longer resolved, and the
share of resamples in which the direction holds under the corrected statistics.

Run after J48:  python scripts/J48b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E6 BEGIN (generated by scripts/J48b_export_numbers.py; do not edit by hand)"
END = "% ---- E6 END"
DS = {"xjtu": "Xjtu", "femto": "Femto"}
CORRECTED = ["range_over_d2", "sd_main_effects", "mad_main_effects", "variance_component"]


def main() -> int:
    d = pd.read_csv(TABLES / "j48_dispersion_extended.csv")
    nine = d[d.pool == "nine"].set_index(["dataset", "statistic"])

    lines = [BEGIN, "% E6: the same dispersion statistics on the pool EXP-4 extended to nine models (J48)"]
    for ds, tag in DS.items():
        rng = nine.loc[(ds, "range")]
        sdm = nine.loc[(ds, "sd_main_effects")]
        mad = nine.loc[(ds, "mad_main_effects")]
        d2 = nine.loc[(ds, "range_over_d2")]
        lines += [
            f"\\newcommand{{\\PoolRangeNine{tag}}}{{{rng.ratio:.1f}}}"
            f"\\newcommand{{\\PoolRangeNineCi{tag}}}{{$[{rng.ratio_lo:.1f}, {rng.ratio_hi:.1f}]$}}"
            f"   % the raw range ratio with nine models, and its bearing-bootstrap interval",
            f"\\newcommand{{\\PoolRangeNineDir{tag}}}{{{100 * rng.share_ratio_gt_1:.1f}\\%}}"
            f"   % share of resamples in which the labeller range is still the larger",
            f"\\newcommand{{\\PoolDTwoNine{tag}}}{{{d2.ratio:.1f}}}"
            f"\\newcommand{{\\PoolSdNine{tag}}}{{{sdm.ratio:.1f}}}"
            f"\\newcommand{{\\PoolMadNine{tag}}}{{{mad.ratio:.1f}}}"
            f"   % the same comparison under the statistics that do not grow with the pool",
            f"\\newcommand{{\\PoolSdNineCi{tag}}}{{$[{sdm.ratio_lo:.1f}, {sdm.ratio_hi:.1f}]$}}"
            f"   % interval of the SD-of-main-effects ratio",
        ]
    # the weakest of the corrected statistics, over both datasets: the number the claim rests on
    worst = min(float(nine.loc[(ds, s)].share_ratio_gt_1) for ds in DS for s in CORRECTED)
    lines.append(f"\\newcommand{{\\PoolCorrectedDirMin}}{{{100 * worst:.1f}\\%}}"
                 f"   % the SMALLEST share, over both datasets and all four corrected statistics")
    lines.append(f"\\newcommand{{\\PoolModels}}{{{int(nine.n_models.max())}}}"
                 f"   % models in the extended pool")
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macro lines into {TARGET.name}")
    for l in lines[2:-1]:
        print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
