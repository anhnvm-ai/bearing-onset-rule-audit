"""J44b -- write the synthetic-robustness macros (J44) into paper/ieee/revision_numbers.tex.

Idempotent between its markers, as the other exporters are.

  j44_robustness.csv   one row per noise x phi x shape x delta x u x rule

Run after J44:  python scripts/J44b_export_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
TARGET = ROOT / "paper" / "ieee" / "revision_numbers.tex"
BEGIN = "% ---- E4 BEGIN (generated by scripts/J44b_export_numbers.py; do not edit by hand)"
END = "% ---- E4 END"


def three(x: float) -> str:
    return f"{x:.3f}"


def main() -> int:
    d = pd.read_csv(TABLES / "j44_robustness.csv")
    phi_ref = sorted(d.phi.unique())[np.argmin([abs(p - 0.367) for p in sorted(d.phi.unique())])]
    zero = d[d.delta_sd == 0]
    step = d[d["shape"] == "step"]

    def far(noise: str, phi: float, fam: str) -> float:
        g = zero[(zero.noise == noise) & np.isclose(zero.phi, phi) & (zero.family == fam)]
        return float(g.false_alarm_rate.median())

    def pre(noise: str, phi: float, fam: str) -> float:
        g = step[(step.noise == noise) & np.isclose(step.phi, phi) & (step.family == fam)]
        return float(g.share_fire_before_change.median())

    lines = [BEGIN,
             "% E4: the known-change simulation under heavier tails, more memory, and with no change at all (J44)"]
    lines += [
        f"\\newcommand{{\\SimPhiRef}}{{{phi_ref:.3f}}}"
        f"   % the measured reference autocorrelation, the one Section S5 uses",
        f"\\newcommand{{\\SimFarChart}}{{{three(far('gauss', phi_ref, 'control chart'))}}}"
        f"\\newcommand{{\\SimFarDetector}}{{{three(far('gauss', phi_ref, 'detector'))}}}"
        f"   % median false-alarm rate on a degradation-free series at the reference phi, by family",
        f"\\newcommand{{\\SimFarChartT}}{{{three(far('t3', phi_ref, 'control chart'))}}}"
        f"\\newcommand{{\\SimFarDetectorT}}{{{three(far('t3', phi_ref, 'detector'))}}}"
        f"   % the same with Student-t(3) innovations",
        f"\\newcommand{{\\SimPreChartT}}{{{three(pre('t3', phi_ref, 'control chart'))}}}"
        f"\\newcommand{{\\SimPreDetectorT}}{{{three(pre('t3', phi_ref, 'detector'))}}}"
        f"   % alarms before the change under Student-t(3) at the reference phi",
        f"\\newcommand{{\\SimPreChartHiPhi}}{{{three(pre('gauss', 0.9, 'control chart'))}}}"
        f"\\newcommand{{\\SimPreDetectorHiPhi}}{{{three(pre('gauss', 0.9, 'detector'))}}}"
        f"   % the same Gaussian at phi = 0.9, which is outside the range these data show",
    ]
    # the worst cell for the detectors, which is what a reader should be told about
    det = step[step.family == "detector"]
    w = det.loc[det.share_fire_before_change.idxmax()]
    lines.append(f"\\newcommand{{\\SimPreDetectorWorst}}{{{three(w.share_fire_before_change)}}}"
                 f"   % the worst cell for the detectors: {w.noise}, phi {w.phi}, delta {w.delta_sd}, u {w.u}")
    lines.append(f"\\newcommand{{\\SimCells}}{{{d.groupby(['noise', 'phi', 'shape', 'delta_sd', 'u'], dropna=False).ngroups}}}"
                 f"   % cells in the grid, each with {int(d.n_series.max()):,} series over the 15 XJTU-SY lengths")
    lines.append(END)

    text = TARGET.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 3} macro lines into {TARGET.name}")
    for l in lines[2:-1]:
        print("   " + l.split("%")[0].strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
